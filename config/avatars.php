<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Avatar Disk
    |--------------------------------------------------------------------------
    |
    | Диск, на который пишутся НОВЫЕ аватары: media_local или media_s3
    | (config/filesystems.php). MEDIA_DRIVER=s3 переключает только эту
    | цель для новых загрузок; существующие файлы разрешаются по
    | сохранённому в БД avatar_disk (конкретный диск), который от режима
    | не зависит.
    |
    */

    'disk' => env('MEDIA_DRIVER', 'local') === 's3' ? 'media_s3' : 'media_local',

    /*
    |--------------------------------------------------------------------------
    | Owned Disks
    |--------------------------------------------------------------------------
    |
    | Диски, файлы которых принадлежат приложению и могут удаляться/читаться
    | как свои. Произвольные внешние URL к этим дискам не относятся.
    |
    */

    'owned_disks' => ['public', 'media_local', 'media_s3'],

    /*
    |--------------------------------------------------------------------------
    | Allowed Prefixes
    |--------------------------------------------------------------------------
    |
    | Префиксы путей, разрешённые для аватаров. Любые объекты вне этих
    | префиксов приложение не читает и не удаляет.
    |
    */

    'allowed_prefixes' => ['avatars/'],

    /*
    |--------------------------------------------------------------------------
    | Legacy URL Prefix
    |--------------------------------------------------------------------------
    |
    | Префикс локальных публичных URL вида /storage/avatars/..., который
    | используется для старых записей и для локального media_local-диска.
    |
    */

    'legacy_url_prefix' => '/storage/',

];
